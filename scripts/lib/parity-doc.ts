import { fieldTargetLabel } from '../../src/parity/field-links.js'
import { UNSUPPORTED_SYMBOLS } from '../../src/parity/overrides.js'
import { WA_EVENT_NAMES } from '../../src/types/events.js'

import type { DocsModel } from './docs-model.js'
import { cell, code, routeOf } from './operations-doc.js'
import { readWwebjsSymbols } from './wwebjs-symbols.js'

// What covers one symbol of whatsapp-web.js, in the order of TDD §6.12: an operation, an event, a
// field, or the reason it is unsupported. `undefined` is a symbol nothing covers.
export function coverageOf(
  symbol: string,
  model: DocsModel,
  eventSymbols: ReadonlySet<string>
): string | undefined {
  const operations = model.operations
    .filter(({ meta }) => meta.wwebjs.includes(symbol))
    .sort((a, b) => a.meta.id.localeCompare(b.meta.id))
  if (operations.length > 0) {
    return operations
      .map(({ meta }) =>
        [
          `operation ${code(meta.id)}`,
          code(routeOf(model, meta.id)),
          meta.socket === undefined ? 'no socket command' : `socket ${code(meta.socket.command)}`
        ].join(', ')
      )
      .join('<br>')
  }
  if (eventSymbols.has(symbol)) return `event ${code(symbol.slice('Events.'.length))}`
  const field = fieldTargetLabel(symbol)
  if (field !== undefined) return field
  const reason = UNSUPPORTED_SYMBOLS[symbol]
  return reason === undefined ? undefined : `unsupported, ${cell(reason)}`
}

export function renderParityMatrix(model: DocsModel): string {
  const eventSymbols = new Set(WA_EVENT_NAMES.map(name => `Events.${name}`))
  const symbols = readWwebjsSymbols().sort()
  const uncovered: string[] = []
  const rows = symbols.map(symbol => {
    const coverage = coverageOf(symbol, model, eventSymbols)
    if (coverage === undefined) uncovered.push(symbol)
    return `| ${code(symbol)} | ${coverage ?? 'NOT COVERED'} |`
  })
  // A matrix that prints "NOT COVERED" would be committed and read as an answer
  if (uncovered.length > 0) {
    throw new Error(`Symbols of whatsapp-web.js that nothing covers: ${uncovered.join(', ')}`)
  }

  return [
    '<!-- GENERATED by `pnpm docs:gen` from the library declarations, @WaOperation.wwebjs, the event list, the field links and the unsupported list. Do not edit by hand. -->',
    '',
    '# whatsapp-web.js parity matrix',
    '',
    `${symbols.length} symbols of the library, each one covered by an operation (with its REST route`,
    'and socket command), an event, a field of a DTO, a request or the environment, or marked',
    'unsupported with the reason. `tests/parity` fails on a symbol that is none of these, so a',
    'library upgrade cannot add one silently.',
    '',
    '| Symbol | Covered by |',
    '| --- | --- |',
    ...rows,
    ''
  ].join('\n')
}
