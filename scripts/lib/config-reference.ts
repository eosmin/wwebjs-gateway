import { z } from 'zod'

import { envSchema } from '../../src/config/env.schema.js'

type JsonSchema = z.core.JSONSchema.JSONSchema

function describeType(property: JsonSchema): string {
  if (property.enum !== undefined)
    return property.enum.map(value => `\`${String(value)}\``).join(', ')
  if (property.format === 'uri') return 'URL'
  if (
    property.type === 'integer' &&
    property.minimum !== undefined &&
    property.maximum !== undefined
  ) {
    return `integer, ${property.minimum} to ${property.maximum}`
  }
  if (property.type === 'string' && property.minLength !== undefined) {
    const unit = property.minLength === 1 ? 'character' : 'characters'
    return `string, ${property.minLength} ${unit} or more`
  }
  return String(property.type)
}

function formatDefault(value: unknown): string {
  if (value === undefined) return ''
  return `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``
}

// The environment variables as the schema defines them, so that the reference cannot drift from it
export function renderConfigReference(): string {
  // "input": a variable with a default is optional for whoever configures the service
  const jsonSchema: JsonSchema = z.toJSONSchema(envSchema, { io: 'input' })
  const required = new Set(jsonSchema.required ?? [])
  const rows = Object.entries(jsonSchema.properties ?? {}).flatMap(([name, property]) => {
    if (typeof property === 'boolean') return []
    const defaultValue = formatDefault(property.default)
    return [
      `| \`${name}\` | ${describeType(property)} | ${required.has(name) ? 'yes' : 'no'} | ${defaultValue} | ${property.description ?? ''} |`
    ]
  })
  return [
    '<!-- GENERATED by `pnpm docs:gen` from src/config/env.schema.ts. Do not edit by hand. -->',
    '',
    '# Configuration reference',
    '',
    'Every environment variable the gateway reads. `.env.example` declares the same set.',
    '',
    '| Variable | Type | Required | Default | Description |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    ''
  ].join('\n')
}
