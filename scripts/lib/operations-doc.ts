import type { RegisteredOperation } from '../../src/api/operation-registry.service.js'

import type { DocsModel } from './docs-model.js'

export const cell = (text: string): string => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ')

export const code = (text: string): string => `\`${text}\``

// `/v1/sessions/:sessionId/chats` -> the names of the segments that start with a colon
export function pathParams(path: string): string[] {
  return [...path.matchAll(/[:{](\w+)}?/g)].map(match => match[1] ?? '')
}

// The route of an operation, written the way the guides write it
export function routeOf(model: DocsModel, id: string): string {
  const route = model.routes.get(id)
  // A placeholder would be committed and read as an answer
  if (route === undefined) throw new Error(`Operation ${id} is not in the OpenAPI document`)
  return `${route.method} ${route.path}`
}

const byId = (a: RegisteredOperation, b: RegisteredOperation): number =>
  a.meta.id.localeCompare(b.meta.id)

// Every operation of the registry, grouped by the object it acts on (the first part of its id)
export function renderOperationsList(model: DocsModel): string {
  const groups = new Map<string, RegisteredOperation[]>()
  for (const operation of [...model.operations].sort(byId)) {
    const group = operation.meta.id.split('.')[0] ?? ''
    groups.set(group, [...(groups.get(group) ?? []), operation])
  }

  const sections = [...groups].flatMap(([group, operations]) => [
    `## ${group}`,
    '',
    '| Operation | REST | Scope | Socket command | wwebjs | Summary |',
    '| --- | --- | --- | --- | --- | --- |',
    ...operations
      .map(({ meta }) =>
        [
          code(meta.id),
          code(routeOf(model, meta.id)),
          code(meta.scope),
          meta.socket === undefined ? 'REST only' : code(meta.socket.command),
          meta.gateway === true ? 'gateway' : meta.wwebjs.map(code).join(', '),
          cell(meta.summary)
        ].join(' | ')
      )
      .map(row => `| ${row} |`),
    ''
  ])

  return [
    '<!-- GENERATED by `pnpm docs:gen` from the @WaOperation registry. Do not edit by hand. -->',
    '',
    '# Operations',
    '',
    `${model.operations.length} operations. Each one is a single controller method declared with`,
    '`@WaOperation`: its REST route, the socket command (when it has one), the OpenAPI document',
    '([`openapi.json`](openapi.json)) and the parity matrix ([`parity-matrix.md`](parity-matrix.md))',
    'all come from that declaration. The scope is what an API key needs to run it (`read`, `send`,',
    '`manage`, `webhooks`, `events`, `admin`); the wwebjs column lists the library symbols it covers',
    'and `gateway` marks what the library has no counterpart for.',
    '',
    ...sections
  ].join('\n')
}
