import { HttpStatus } from '@nestjs/common'

import { ERROR_DEFINITIONS, type ErrorCode } from '../../src/common/errors.js'

// "UNPROCESSABLE_ENTITY" -> "Unprocessable Entity"
export function statusName(status: number): string {
  return (HttpStatus[status] ?? String(status))
    .split('_')
    .map(word => word.charAt(0) + word.slice(1).toLowerCase())
    .join(' ')
}

// The error codes as common/errors.ts defines them, so that the reference cannot drift from it
export function renderErrors(): string {
  const rows = (
    Object.entries(ERROR_DEFINITIONS) as [ErrorCode, { status: number; meaning: string }][]
  )
    .sort(([, a], [, b]) => a.status - b.status)
    .map(
      ([code, { status, meaning }]) =>
        `| \`${code}\` | ${status} ${statusName(status)} | ${meaning} |`
    )
  return [
    '<!-- GENERATED by `pnpm docs:gen` from src/common/errors.ts. Do not edit by hand. -->',
    '',
    '# Errors',
    '',
    'Every error answers with the same body:',
    '',
    '```json',
    '{ "error": { "code": "SESSION_NOT_READY", "message": "…", "details": {}, "requestId": "…" } }',
    '```',
    '',
    '`code` is stable and meant for programs; `message` is for people and may change. `details` is',
    'optional: it carries extra data of some codes (the issues of a `VALIDATION_ERROR`, the rule of a',
    '`POLICY_BLOCKED`).',
    '`requestId` repeats the `x-request-id` header, so quote it when reporting a problem.',
    '',
    '| Code | HTTP status | Meaning |',
    '| --- | --- | --- |',
    ...rows,
    '',
    'A send accepted asynchronously never answers with its failure: `UNKNOWN_OUTCOME`, `ACK_ERROR`,',
    '`POLICY_DELAY_EXCEEDED` and `SESSION_NOT_READY` reach the consumer as the reason of the',
    '`message_failed` event. The status of the table is what a synchronous send (`wait=true`) answers.',
    ''
  ].join('\n')
}
