import { z } from 'zod'

import { WA_EVENT_NAMES, WA_EVENTS, eventEnvelope } from '../../src/types/events.js'

import { exampleOf } from './json-schema-example.js'

type JsonSchema = z.core.JSONSchema.JSONSchema
type Definitions = Record<string, JsonSchema>

const refName = (ref: string): string => ref.slice(ref.lastIndexOf('/') + 1)

// A schema with an id comes out of toJSONSchema as a reference into $defs
function resolved(schema: z.ZodType): {
  top: JsonSchema
  root: JsonSchema
  definitions: Definitions
} {
  const { $defs = {}, ...top } = z.toJSONSchema(schema) as JsonSchema & { $defs?: Definitions }
  const root = top.$ref === undefined ? top : ($defs[refName(top.$ref)] ?? top)
  return { top, root, definitions: $defs }
}

function describeType(schema: JsonSchema): string {
  if (schema.$ref !== undefined) {
    const name = refName(schema.$ref)
    // z.json() refers to itself
    return name.startsWith('__schema') ? 'any JSON' : `[${name}](#${name.toLowerCase()})`
  }
  if (schema.const !== undefined) return `\`${String(schema.const)}\``
  if (schema.enum !== undefined) return schema.enum.map(value => `\`${String(value)}\``).join(', ')
  if (schema.anyOf !== undefined) {
    return schema.anyOf
      .map(option => (typeof option === 'object' ? describeType(option) : ''))
      .join(' or ')
  }
  if (Array.isArray(schema.type)) return schema.type.join(' or ')
  if (schema.type === 'array') {
    const { items } = schema
    return `${typeof items === 'object' && !Array.isArray(items) ? describeType(items) : 'any'}[]`
  }
  if (schema.type === 'string' && schema.format === 'date-time') return 'ISO date'
  return schema.type === undefined ? 'any' : String(schema.type)
}

const jsonBlock = (value: unknown): string[] => ['```json', JSON.stringify(value, null, 2), '```']

const TABLE_HEAD = ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |']

function fieldTable(schema: JsonSchema): string[] {
  const required = new Set(schema.required ?? [])
  const rows = Object.entries(schema.properties ?? {}).flatMap(([name, property]) =>
    typeof property === 'boolean'
      ? []
      : [
          `| \`${name}\` | ${describeType(property)} | ${required.has(name) ? 'yes' : 'no'} | ${property.description ?? ''} |`
        ]
  )
  return [...TABLE_HEAD, ...rows]
}

// Every event with when it fires, the shape of its `data` and a full example, then the data types
// they share; all of it from the schemas of src/types, so that the reference cannot drift from them
export function renderEvents(): string {
  const shared: Definitions = {}

  const sections = WA_EVENT_NAMES.flatMap(name => {
    const payload = resolved(WA_EVENTS[name].payload)
    Object.assign(shared, payload.definitions)
    const data =
      payload.top.$ref !== undefined
        ? [`\`data\` is a ${describeType(payload.top)}.`]
        : Object.keys(payload.root.properties ?? {}).length === 0
          ? ['`data` is an empty object.']
          : ['`data` holds:', '', ...fieldTable(payload.root)]
    // An event that carries a data type shows it once, under Data types, instead of in each event
    const carriesDataType = JSON.stringify(payload.top).includes('"$ref"')
    const envelope = resolved(eventEnvelope(name))
    return [
      `### \`${name}\``,
      '',
      WA_EVENTS[name].fires,
      '',
      ...data,
      '',
      ...(carriesDataType ? [] : [...jsonBlock(exampleOf(envelope.top, envelope.definitions)), ''])
    ]
  })

  const types = Object.entries(shared)
    .filter(([name]) => !name.startsWith('__schema'))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .flatMap(([name, schema]) => [
      `### ${name}`,
      '',
      ...fieldTable(schema),
      '',
      ...jsonBlock(exampleOf(schema, shared)),
      ''
    ])

  return [
    '<!-- GENERATED by `pnpm docs:gen` from src/types. Do not edit by hand. -->',
    '',
    '# Events',
    '',
    'Webhooks and Socket.IO deliver every event in the same envelope:',
    '',
    '- `id` is unique per event; use it to drop duplicates.',
    '- `seq` grows strictly per session and follows the order of the conversation, because it is assigned',
    '  after the order buffer. Delivery is at least once, so a consumer has to be idempotent.',
    '- `data` is always a data type of this page, never a raw WhatsApp Web object.',
    '',
    'The first events are the ones whatsapp-web.js emits; from `session_status` on, the gateway makes them up.',
    '',
    '## Events',
    '',
    ...sections,
    '## Data types',
    '',
    'The data types that events carry. The others (contacts, channels, labels…) are described with the operations that return them.',
    '',
    ...types
  ].join('\n')
}
