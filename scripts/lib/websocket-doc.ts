import { REST_ONLY_OPERATIONS } from '../../src/parity/overrides.js'

import type { DocsModel } from './docs-model.js'
import { cell, code, pathParams, routeOf } from './operations-doc.js'

// The operations a socket can run, and the ones it cannot with the reason (TDD §6.10)
export function renderWebsocketCommands(model: DocsModel): string {
  const withSocket = model.operations
    .filter(({ meta }) => meta.socket !== undefined)
    .sort((a, b) => (a.meta.socket?.command ?? '').localeCompare(b.meta.socket?.command ?? ''))
  const restOnly = model.operations
    .filter(({ meta }) => meta.socket === undefined)
    .sort((a, b) => a.meta.id.localeCompare(b.meta.id))

  const commandRows = withSocket.map(({ meta }) => {
    const params = pathParams(routeOf(model, meta.id).split(' ')[1] ?? '').filter(
      name => name !== 'sessionId'
    )
    return `| ${[
      code(meta.socket?.command ?? ''),
      code(meta.id),
      code(meta.scope),
      params.length === 0 ? 'none' : params.map(code).join(', '),
      cell(meta.summary)
    ].join(' | ')} |`
  })

  const restOnlyRows = restOnly.map(({ meta }) => {
    const reason = REST_ONLY_OPERATIONS[meta.id]
    if (reason === undefined) {
      throw new Error(
        `Operation ${meta.id} has no socket command and no REST_ONLY_OPERATIONS reason`
      )
    }
    return `| ${[code(meta.id), code(routeOf(model, meta.id)), cell(reason)].join(' | ')} |`
  })

  return [
    '<!-- GENERATED by `pnpm docs:gen` from @WaOperation.socket and REST_ONLY_OPERATIONS. Do not edit by hand. -->',
    '',
    '# Socket commands',
    '',
    `${withSocket.length} operations run as a socket command, with the same scope, validation and`,
    'errors as their REST route. A command is sent as',
    '`command { op, sessionId?, params?, idempotencyKey? }`: `op` is the name of the first column,',
    '`sessionId` stands for the `:sessionId` of the route, and `params` holds the other path',
    'parameters (listed here) together with the body or the query of the route. The ack, the rate',
    'limits and the handshake are in [`websocket.md`](websocket.md); the fields of each `params` are',
    'those of the operation in [`openapi.json`](openapi.json).',
    '',
    '| Command | Operation | Scope | Path params | Summary |',
    '| --- | --- | --- | --- | --- |',
    ...commandRows,
    '',
    '## REST only',
    '',
    `${restOnly.length} operations have no socket command, each for a reason:`,
    '',
    '| Operation | REST | Reason |',
    '| --- | --- | --- |',
    ...restOnlyRows,
    ''
  ].join('\n')
}
